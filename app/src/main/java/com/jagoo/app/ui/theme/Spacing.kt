package com.jagoo.app.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Tokens de espaciado centralizados de Jagoo.
 * Todos los valores son múltiplos de 4 dp para mantener una cuadrícula consistente.
 * Uso: JagooSpacing.md en vez de 16.dp literal.
 */
object JagooSpacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
    val xxl = 48.dp
}
